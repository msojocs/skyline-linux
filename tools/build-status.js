'use strict';

// Build-step freshness: which native artifacts are stale relative to the
// sources, and which commands rebuild them.
//
//   node tools/build-status.js                    # report every step
//   node tools/build-status.js --check engine-debug,kernel
//   node tools/build-status.js --json
//
// Each build step records the fingerprints of the inputs it consumed in a
// stamp file next to its outputs (written by the native/engine/*.sh scripts):
//
//   fingerprint <runtime|dart-ui|app-compat> [--root DIR]
//   stamp patched-sdk [--dir DIR]
//   stamp engine --mode debug|release --dart-ui applied|unpatched
//   stamp kernel
//   stamp aot --app-dir DIR [--patched-sdk]
//
// The embedded runtime also carries its source fingerprint inside
// libflutter_engine.so (`SkylineRuntimeBuildId`, generated by build-engine.sh
// from the copies it compiles), so a copied or downloaded engine is checked
// without trusting a stamp.

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const repoRoot = path.resolve(__dirname, '..');
const engineDir = path.join(repoRoot, 'native', 'engine');
const runtimeDir = path.join(repoRoot, 'native', 'runtime');
const appCompatDir = path.join(engineDir, 'app_compat');
const workDir = process.env.SKYLINE_ENGINE_WORK || path.join(engineDir, 'work');
const skylineApp = path.join(workDir, 'skyline-app');

const RUNTIME_ID_MARKER = 'SKYLINE_RUNTIME_BUILD_ID=';
const STAMP = 'skyline-build.json';

function engineStage(mode) {
  return path.join(engineDir, 'out', `linux-x64-${mode}`);
}

function patchedSdkDir() {
  if (process.env.SKYLINE_PATCHED_SDK) return process.env.SKYLINE_PATCHED_SDK;
  const stage = process.env.SKYLINE_ENGINE_STAGE || engineStage('debug');
  return path.join(stage, 'patched_sdk');
}

// -- Fingerprints ------------------------------------------------------------

function sha256(data) {
  return crypto.createHash('sha256').update(data).digest('hex');
}

// Order-independent hash of `relPaths` under `baseDir` (names + contents).
function hashFiles(baseDir, relPaths) {
  const hash = crypto.createHash('sha256');
  for (const rel of [...relPaths].sort()) {
    const file = path.join(baseDir, rel);
    const digest = fs.existsSync(file) ? sha256(fs.readFileSync(file)) : 'missing';
    hash.update(`${rel}\0${digest}\n`);
  }
  return hash.digest('hex');
}

function listFiles(dir, suffix) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(name => name.endsWith(suffix)).sort();
}

// Every file listed in native/runtime/sources.txt (all sections).
function runtimeSources() {
  const files = [];
  const manifest = fs.readFileSync(path.join(runtimeDir, 'sources.txt'), 'utf8');
  for (const raw of manifest.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || /^\[[a-z]+\]$/.test(line)) continue;
    files.push(line);
  }
  return files;
}

// `root` lets build-engine.sh hash the copies inside the engine checkout.
function runtimeFingerprint(root = runtimeDir) {
  return hashFiles(root, runtimeSources());
}

function dartUiFingerprint() {
  return hashFiles(engineDir, [
    ...listFiles(path.join(engineDir, 'patches'), '.patch').map(name => `patches/${name}`),
    ...listFiles(path.join(engineDir, 'dart_ui_compat'), '.dart').map(name => `dart_ui_compat/${name}`),
  ]);
}

function appCompatPatches() {
  return listFiles(appCompatDir, '.patch');
}

function appCompatFingerprint() {
  return hashFiles(appCompatDir, appCompatPatches());
}

function fingerprints() {
  return {
    runtime: runtimeFingerprint(),
    dartUi: dartUiFingerprint(),
    appCompat: appCompatFingerprint(),
  };
}

// Reads the runtime fingerprint compiled into a library without loading it.
// Returns null when the library has no marker (built before the marker
// existed), 'unversioned' for builds without a generated ID.
function readRuntimeBuildId(libPath) {
  const marker = Buffer.from(RUNTIME_ID_MARKER);
  const idPattern = /^(?:[0-9a-f]{64}|unversioned)/;
  const chunkSize = 16 * 1024 * 1024;
  const overlap = marker.length + 64;
  const fd = fs.openSync(libPath, 'r');
  try {
    const buffer = Buffer.alloc(chunkSize + overlap);
    let carried = 0;
    for (;;) {
      const read = fs.readSync(fd, buffer, carried, chunkSize, null);
      const length = carried + read;
      if (length === 0) return null;
      const window = buffer.subarray(0, length);
      let index = window.indexOf(marker);
      while (index >= 0) {
        const tail = window.subarray(index + marker.length, index + marker.length + 64).toString('latin1');
        const match = idPattern.exec(tail);
        if (match) return match[0];
        index = window.indexOf(marker, index + 1);
      }
      if (read === 0) return null;
      carried = Math.min(overlap, length);
      buffer.copy(buffer, 0, length - carried, length);
    }
  } finally {
    fs.closeSync(fd);
  }
}

// -- app_compat patches on the reconstructed sources ---------------------------

// The work tree lives inside this repository (ignored), so stop repository
// discovery at its parent: git apply then patches it as a plain directory.
function gitApply(appDir, args) {
  return spawnSync('git', ['apply', ...args], {
    cwd: appDir,
    encoding: 'utf8',
    env: { ...process.env, GIT_CEILING_DIRECTORIES: path.dirname(appDir) },
  });
}

// { applied: [...], pending: [...], diverged: [...] } for the app_compat patches.
function appCompatState(appDir = skylineApp) {
  const state = { applied: [], pending: [], diverged: [] };
  for (const name of appCompatPatches()) {
    const patch = path.join(appCompatDir, name);
    if (gitApply(appDir, ['--reverse', '--check', patch]).status === 0) {
      state.applied.push(name);
    } else if (gitApply(appDir, ['--check', patch]).status === 0) {
      state.pending.push(name);
    } else {
      state.diverged.push(name);
    }
  }
  return state;
}

// -- Stamps --------------------------------------------------------------------

function stampFiles() {
  return {
    patchedSdk: path.join(patchedSdkDir(), STAMP),
    engine: mode => path.join(engineStage(mode), STAMP),
    kernel: path.join(skylineApp, 'build', 'skyline-build.kernel.json'),
    aot: appDir => path.join(appDir, 'build', 'skyline-build.aot.json'),
  };
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

function sourceRevision() {
  const head = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' });
  const dirty = spawnSync('git', ['status', '--porcelain', '--untracked-files=no'], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  if (head.status !== 0) return null;
  return head.stdout.trim() + (dirty.stdout.trim() ? '-dirty' : '');
}

function writeStamp(file, fields) {
  const stamp = { ...fields, commit: sourceRevision(), builtAt: new Date().toISOString() };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(stamp, null, 2) + '\n');
  return stamp;
}

// dart:ui inputs of the staged patched SDK (null when it has no stamp).
function patchedSdkDartUi() {
  const stamp = readJson(stampFiles().patchedSdk);
  return stamp ? stamp.dartUi : null;
}

function writeStepStamp(step, options) {
  const files = stampFiles();
  const current = fingerprints();
  switch (step) {
    case 'patched-sdk':
      return writeStamp(options.dir ? path.join(options.dir, STAMP) : files.patchedSdk, {
        step,
        dartUi: current.dartUi,
      });
    case 'engine': {
      if (!['debug', 'release'].includes(options.mode)) throw new Error('stamp engine needs --mode debug|release');
      if (!['applied', 'unpatched'].includes(options.dartUi)) {
        throw new Error('stamp engine needs --dart-ui applied|unpatched');
      }
      const lib = path.join(engineStage(options.mode), 'libflutter_engine.so');
      return writeStamp(files.engine(options.mode), {
        step,
        mode: options.mode,
        dartUi: options.dartUi === 'applied' ? current.dartUi : null,
        runtime: fs.existsSync(lib) ? readRuntimeBuildId(lib) : null,
      });
    }
    case 'kernel': {
      const state = appCompatState(skylineApp);
      return writeStamp(files.kernel, {
        step,
        dartUi: patchedSdkDartUi(),
        appCompat: state.pending.length || state.diverged.length ? null : current.appCompat,
      });
    }
    case 'aot': {
      const appDir = path.resolve(options.appDir || skylineApp);
      let appCompat = null;
      if (appDir === path.resolve(skylineApp)) {
        const state = appCompatState(appDir);
        if (!state.pending.length && !state.diverged.length) appCompat = current.appCompat;
      }
      return writeStamp(files.aot(appDir), {
        step,
        dartUi: options.patchedSdk ? patchedSdkDartUi() : null,
        appCompat,
      });
    }
    default:
      throw new Error(`unknown stamp step: ${step}`);
  }
}

// -- Status --------------------------------------------------------------------

const RUNTIME_EMBED = {
  debug: 'npm run runtime:embed',
  release: 'npm run runtime:embed -- --runtime-mode release',
};

// Commands in pipeline order, so the printed fix list is runnable top-down.
const COMMAND_ORDER = [
  'npm run ui:patch',
  'npm run kernel:skyline -- --refresh-sources',
  RUNTIME_EMBED.debug,
  RUNTIME_EMBED.release,
  'npm run kernel:skyline',
  'npm run devtools:aot',
];

function stepResult(name, problems, fixes, missing = false) {
  return {
    name,
    status: missing ? 'missing' : problems.length ? 'stale' : 'ok',
    problems,
    fixes,
  };
}

function statusPatchedSdk(current) {
  const dill = path.join(patchedSdkDir(), 'platform_strong.dill');
  if (!fs.existsSync(dill)) return stepResult('patched-sdk', ['patched SDK not built'], ['npm run ui:patch'], true);
  const stamp = readJson(stampFiles().patchedSdk);
  const problems = [];
  if (!stamp) problems.push('no build stamp (built before stamps existed)');
  else if (stamp.dartUi !== current.dartUi) problems.push('dart:ui patches changed since the SDK was built');
  return stepResult('patched-sdk', problems, problems.length ? ['npm run ui:patch'] : []);
}

function statusEngine(mode, current) {
  const name = `engine-${mode}`;
  const lib = path.join(engineStage(mode), 'libflutter_engine.so');
  if (!fs.existsSync(lib)) {
    return stepResult(name, ['engine not built'], [RUNTIME_EMBED[mode]], true);
  }
  const problems = [];
  const fixes = [];
  const runtimeId = readRuntimeBuildId(lib);
  if (runtimeId === null) {
    problems.push('engine has no runtime build ID (built before IDs existed, or no embedded runtime)');
  } else if (runtimeId !== current.runtime) {
    problems.push('native/runtime sources changed since the engine was built');
  }
  const stamp = readJson(stampFiles().engine(mode));
  if (!stamp) {
    problems.push('no build stamp (built before stamps existed)');
  } else if (stamp.dartUi !== current.dartUi) {
    problems.push(stamp.dartUi === null
      ? 'engine was built from a checkout without the current dart:ui patches'
      : 'dart:ui patches changed since the engine was built');
    fixes.push('npm run ui:patch');
  }
  if (problems.length) fixes.push(RUNTIME_EMBED[mode]);
  return stepResult(name, problems, fixes);
}

function statusAppSources() {
  const root = path.join(skylineApp, 'packages', 'sample', 'lib', 'devtools.dart');
  if (!fs.existsSync(root)) {
    return stepResult('app-sources', ['sources not reconstructed'], ['npm run kernel:skyline'], true);
  }
  const state = appCompatState(skylineApp);
  const problems = [];
  const fixes = [];
  if (state.diverged.length) {
    problems.push(`app_compat patches neither applied nor applicable: ${state.diverged.join(', ')}`);
    fixes.push('npm run kernel:skyline -- --refresh-sources');
  }
  if (state.pending.length) {
    problems.push(`app_compat patches not applied: ${state.pending.join(', ')}`);
    fixes.push('npm run kernel:skyline');
  }
  return stepResult('app-sources', problems, fixes);
}

function statusDartArtifact(name, artifact, stampFile, current, fix) {
  if (!fs.existsSync(artifact)) return stepResult(name, [`${path.basename(artifact)} not built`], [fix], true);
  const stamp = readJson(stampFile);
  const problems = [];
  if (!stamp) {
    problems.push('no build stamp (built before stamps existed)');
  } else {
    if (stamp.appCompat !== current.appCompat) problems.push('app_compat patches changed since it was built');
    if (stamp.dartUi !== current.dartUi) problems.push('dart:ui patches changed since it was built');
  }
  return stepResult(name, problems, problems.length ? [fix] : []);
}

const STEPS = {
  'patched-sdk': current => statusPatchedSdk(current),
  'engine-debug': current => statusEngine('debug', current),
  'engine-release': current => statusEngine('release', current),
  'app-sources': () => statusAppSources(),
  kernel: current => statusDartArtifact(
    'kernel',
    path.join(skylineApp, 'build', 'flutter_assets', 'kernel_blob.bin'),
    stampFiles().kernel,
    current,
    'npm run kernel:skyline'),
  aot: current => statusDartArtifact(
    'aot',
    path.join(skylineApp, 'build', 'libapp.so'),
    stampFiles().aot(skylineApp),
    current,
    'npm run devtools:aot'),
};

function buildStatus(names = Object.keys(STEPS)) {
  const current = fingerprints();
  return names.map(name => {
    const step = STEPS[name];
    if (!step) throw new Error(`unknown build step: ${name} (expected ${Object.keys(STEPS).join(', ')})`);
    return step(current);
  });
}

function orderedFixes(results) {
  const wanted = new Set(results.flatMap(result => result.fixes));
  return [...COMMAND_ORDER.filter(command => wanted.has(command)),
    ...[...wanted].filter(command => !COMMAND_ORDER.includes(command))];
}

// Human-readable problems for steps that are not current (empty when fresh).
function buildProblems(names) {
  const results = buildStatus(names).filter(result => result.status !== 'ok');
  if (!results.length) return [];
  return [
    ...results.map(result => `${result.name}: ${result.status} (${result.problems.join('; ')})`),
    `rebuild with: ${orderedFixes(results).join(' && ')}`,
  ];
}

// -- CLI -------------------------------------------------------------------------

function optionValue(args, name) {
  const index = args.indexOf(name);
  if (index >= 0) return args[index + 1];
  const inline = args.find(arg => arg.startsWith(`${name}=`));
  return inline ? inline.slice(name.length + 1) : undefined;
}

function printReport(results) {
  const width = Math.max(...results.map(result => result.name.length));
  for (const result of results) {
    const line = `${result.name.padEnd(width)}  ${result.status.padEnd(7)}  ${result.problems.join('; ')}`;
    console.log(line.trimEnd());
  }
  const fixes = orderedFixes(results);
  if (fixes.length) {
    console.log('\nRebuild, in order:');
    for (const command of fixes) console.log(`  ${command}`);
  }
}

function main(args) {
  const [command] = args;
  if (command === 'fingerprint') {
    const kind = args[1];
    const root = optionValue(args, '--root');
    const value = {
      runtime: () => runtimeFingerprint(root ? path.resolve(root) : runtimeDir),
      'dart-ui': dartUiFingerprint,
      'app-compat': appCompatFingerprint,
    }[kind];
    if (!value) throw new Error('fingerprint needs runtime, dart-ui or app-compat');
    process.stdout.write(`${value()}\n`);
    return 0;
  }
  if (command === 'stamp') {
    const stamp = writeStepStamp(args[1], {
      dir: optionValue(args, '--dir'),
      mode: optionValue(args, '--mode'),
      dartUi: optionValue(args, '--dart-ui'),
      appDir: optionValue(args, '--app-dir'),
      patchedSdk: args.includes('--patched-sdk'),
    });
    console.error(`[build-status] stamped ${args[1]}: ${JSON.stringify(stamp)}`);
    return 0;
  }
  const check = optionValue(args, '--check');
  const names = check ? check.split(',').map(name => name.trim()).filter(Boolean) : undefined;
  const results = buildStatus(names);
  if (args.includes('--json')) {
    console.log(JSON.stringify({ fingerprints: fingerprints(), steps: results }, null, 2));
  } else {
    printReport(results);
  }
  return check && results.some(result => result.status !== 'ok') ? 1 : 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`[build-status] error: ${error.message}`);
    process.exitCode = 2;
  }
}

