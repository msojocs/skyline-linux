'use strict';

// Environment variable registry (tools/env-vars.json): generated outputs and
// the code scan that keeps it complete.
//
//   node tools/env-doc.js           # write docs/env.md and
//                                   # native/include/skyline/config_vars.inc
//   node tools/env-doc.js --check   # fail when they are stale or the code
//                                   # reads an unregistered SKYLINE_* variable
//
// Native code reads its variables through skyline::config
// (native/include/skyline/config.h), whose table is the generated .inc; the
// .inc carries no descriptions, so editing the documentation does not change
// the runtime sources compiled into the engine.

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const repoRoot = path.resolve(__dirname, '..');
const registryPath = path.join(__dirname, 'env-vars.json');
const docPath = path.join(repoRoot, 'docs', 'env.md');
const nativeTablePath = path.join(repoRoot, 'native', 'include', 'skyline', 'config_vars.inc');
// The only native file allowed to call getenv() for SKYLINE_* variables.
const configSource = 'native/common/config.cc';

const NATIVE_COMPONENTS = new Set(['native', 'runtime', 'addon', 'host', 'shared-memory']);
const TYPES = new Set(['flag', 'string', 'path', 'int', 'enum']);

function loadRegistry(file = registryPath) {
  const registry = JSON.parse(fs.readFileSync(file, 'utf8'));
  const names = new Set();
  for (const variable of registry.variables) {
    if (!/^SKYLINE_[A-Z0-9_]+$/.test(variable.name)) {
      throw new Error(`${variable.name}: names must start with SKYLINE_`);
    }
    if (names.has(variable.name)) throw new Error(`${variable.name}: registered twice`);
    names.add(variable.name);
    if (!TYPES.has(variable.type)) throw new Error(`${variable.name}: unknown type ${variable.type}`);
    if (variable.type === 'enum' && !(variable.values || []).length) {
      throw new Error(`${variable.name}: enum without values`);
    }
    for (const component of variable.components || []) {
      if (!registry.components[component]) {
        throw new Error(`${variable.name}: unknown component ${component}`);
      }
    }
    if (!variable.description) throw new Error(`${variable.name}: missing description`);
  }
  return registry;
}

function isNative(variable) {
  return variable.components.some(component => NATIVE_COMPONENTS.has(component));
}

// SKYLINE_APP_SERVICE_DEBUG -> kAppServiceDebug
function nativeId(name) {
  return 'k' + name.replace(/^SKYLINE_/, '').toLowerCase()
    .replace(/(^|_)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase());
}

function cString(value) {
  return JSON.stringify(String(value));
}

function renderNativeTable(registry) {
  const lines = [
    '// Generated by tools/env-doc.js from tools/env-vars.json; do not edit.',
    '// SKYLINE_CONFIG_VAR(id, name, type, default)',
  ];
  for (const variable of registry.variables.filter(isNative)) {
    const type = 'k' + variable.type[0].toUpperCase() + variable.type.slice(1);
    lines.push(`SKYLINE_CONFIG_VAR(${nativeId(variable.name)}, ${cString(variable.name)}, ` +
      `${type}, ${cString(variable.default ?? '')})`);
  }
  return lines.join('\n') + '\n';
}

function markdownCell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function renderDoc(registry) {
  const lines = [
    '# 环境变量参考',
    '',
    '> 由 `npm run env:doc` 从 `tools/env-vars.json` 生成，请勿手工编辑。',
    '> 新增或修改变量时编辑注册表，再重新生成本文件与',
    '> `native/include/skyline/config_vars.inc`；`test/env-registry.test.js`',
    '> 检查代码读取的每个 `SKYLINE_*` 变量都已注册。',
    '',
    '原生组件（runtime、addon、host、shared-memory）通过 `skyline::config`',
    '（`native/include/skyline/config.h`）读取变量：每个进程在第一次读取时取一次',
    '环境快照，之后修改环境不再生效。`flag` 类型除未设置、空串、`0`、`false`、',
    '`off`、`no` 之外都视为开启。',
    '',
  ];
  const order = Object.keys(registry.components);
  const groups = new Map(order.map(component => [component, []]));
  for (const variable of registry.variables) groups.get(variable.components[0]).push(variable);
  for (const component of order) {
    const variables = groups.get(component);
    if (!variables.length) continue;
    lines.push(`## ${component}`, '', registry.components[component], '');
    lines.push('| 变量 | 类型 | 默认值 | 组件 | 说明 |', '| --- | --- | --- | --- | --- |');
    for (const variable of variables) {
      const type = variable.type === 'enum' ? `enum: ${variable.values.join(' / ')}` : variable.type;
      const fallback = variable.default ? `\`${variable.default}\`` : '—';
      lines.push(`| \`${variable.name}\` | ${type} | ${markdownCell(fallback)} | ` +
        `${variable.components.join(', ')} | ${markdownCell(variable.description)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// -- Code scan -----------------------------------------------------------------------

// Tracked and new (not ignored) files of the working tree.
function trackedFiles() {
  const result = spawnSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  if (result.status !== 0) throw new Error(`git ls-files failed: ${result.stderr}`);
  return [...new Set(result.stdout.split('\0').filter(Boolean))]
    .filter(file => fs.existsSync(path.join(repoRoot, file)));
}

const NAME = 'SKYLINE_[A-Z0-9_]+';
// Patterns that read or set an environment variable, by file kind.
const PATTERNS = {
  js: [
    new RegExp(`process\\.env\\.(${NAME})`, 'g'),
    new RegExp(`process\\.env\\[['"](${NAME})['"]\\]`, 'g'),
    new RegExp(`\\benv\\.(${NAME})\\b`, 'g'),
    // Keys of env objects passed to child processes: `{ SKYLINE_X: ... }`.
    new RegExp(`(?<![\\w.])(${NAME})\\s*:(?!:)`, 'g'),
  ],
  shell: [
    new RegExp(`\\$\\{?(${NAME})\\b`, 'g'),
    new RegExp(`(?<![\\w-])(${NAME})=`, 'g'),
  ],
  native: [new RegExp(`getenv\\(\\s*"(${NAME})"`, 'g')],
  dart: [new RegExp(`environment\\[['"](${NAME})['"]\\]`, 'g')],
};

function kindOf(file) {
  if (/\.(c|cc|cpp|h|hh)$/.test(file)) return 'native';
  if (/\.(js|mjs|cjs)$/.test(file)) return 'js';
  if (/\.(sh|ya?ml)$/.test(file) || file === 'package.json') return 'shell';
  if (/\.(dart|patch)$/.test(file)) return 'dart';
  return null;
}

// Map of variable name -> files that read or set it.  Docs, the registry,
// this scanner and third-party code are not scanned.
function scanReferences() {
  const references = new Map();
  const skipped = new Set([registryPath, __filename].map(file => path.relative(repoRoot, file)));
  for (const file of trackedFiles()) {
    if (/(^|\/)third_party\//.test(file) || file.startsWith('docs/') || skipped.has(file)) {
      continue;
    }
    const kind = kindOf(file);
    if (!kind) continue;
    const text = fs.readFileSync(path.join(repoRoot, file), 'utf8');
    const patterns = kind === 'dart' ? [...PATTERNS.dart, ...PATTERNS.shell] : PATTERNS[kind];
    for (const pattern of patterns) {
      for (const match of text.matchAll(pattern)) {
        if (!references.has(match[1])) references.set(match[1], new Set());
        references.get(match[1]).add(file);
      }
    }
  }
  return references;
}

// Native files that read SKYLINE_* variables without skyline::config.
function nativeGetenvViolations(references = scanReferences()) {
  const violations = [];
  for (const [name, files] of references) {
    for (const file of files) {
      if (kindOf(file) === 'native' && file !== configSource) violations.push(`${file}: ${name}`);
    }
  }
  return violations.sort();
}

// Registered native variables that no native code reads through
// skyline::config.
function unusedNativeVariables(registry) {
  const ids = new Set();
  for (const file of trackedFiles()) {
    if (!/^native\/(runtime|src|host|shared-memory\/src|common)\/.*\.(cc|hh|h)$/.test(file)) continue;
    const text = fs.readFileSync(path.join(repoRoot, file), 'utf8');
    for (const match of text.matchAll(/\bconfig::(k[A-Z]\w*)/g)) ids.add(match[1]);
  }
  return registry.variables.filter(isNative)
    .filter(variable => !ids.has(nativeId(variable.name)))
    .map(variable => variable.name);
}

// Problems that make --check (and the registry test) fail.
function registryProblems(registry = loadRegistry()) {
  const problems = [];
  if (!fs.existsSync(docPath) || fs.readFileSync(docPath, 'utf8') !== renderDoc(registry)) {
    problems.push('docs/env.md is stale (run npm run env:doc)');
  }
  if (!fs.existsSync(nativeTablePath) ||
      fs.readFileSync(nativeTablePath, 'utf8') !== renderNativeTable(registry)) {
    problems.push('native/include/skyline/config_vars.inc is stale (run npm run env:doc)');
  }
  const registered = new Set(registry.variables.map(variable => variable.name));
  const references = scanReferences();
  for (const [name, files] of references) {
    if (!registered.has(name) && !(registry.notVariables || {})[name]) {
      problems.push(`${name} is not registered in tools/env-vars.json (${[...files].join(', ')})`);
    }
  }
  for (const variable of registry.variables) {
    if (!references.has(variable.name) && !isNative(variable)) {
      problems.push(`${variable.name} is registered but nothing reads it`);
    }
  }
  for (const name of unusedNativeVariables(registry)) {
    problems.push(`${name} is registered for native code but no skyline::config call reads it`);
  }
  for (const violation of nativeGetenvViolations(references)) {
    problems.push(`${violation} is read with getenv(); use skyline::config`);
  }
  return problems;
}

function main(args) {
  const registry = loadRegistry();
  if (args.includes('--check')) {
    const problems = registryProblems(registry);
    for (const problem of problems) console.error(`[env-doc] ${problem}`);
    return problems.length ? 1 : 0;
  }
  fs.writeFileSync(docPath, renderDoc(registry));
  fs.writeFileSync(nativeTablePath, renderNativeTable(registry));
  console.log(`[env-doc] wrote ${path.relative(repoRoot, docPath)} and ` +
    `${path.relative(repoRoot, nativeTablePath)} (${registry.variables.length} variables)`);
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`[env-doc] error: ${error.message}`);
    process.exitCode = 2;
  }
}

module.exports = {
  loadRegistry,
  nativeId,
  registryProblems,
  renderDoc,
  renderNativeTable,
  scanReferences,
};
