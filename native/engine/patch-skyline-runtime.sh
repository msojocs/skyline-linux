#!/usr/bin/env bash
# Installs the embedded Skyline runtime into the pinned engine checkout and
# builds `libflutter_engine.so` with the 73 addon exports and the synthetic
# Skyline page path.
#
#   bash native/engine/patch-skyline-runtime.sh [--check] [--no-build]
#                                                 [--runtime-mode debug|release]
#
# The embedded build has the full Dart API (statically linked), so it can call
# the real `package:skyline` widget constructors (NewYGNode/NewDecoratedBox/
# CreatePageRoute).  The runtime sources are copied from `native/runtime`
# (ordered by `sources.txt`): the [common] translation units build the
# standalone DL-only library, the [embedded] ones are added to the engine's
# embedder target with SKYLINE_EMBEDDED=1.  `native/build/libskyline.so` stays
# available for bootstrap-only tests.
#
# After building, `libskyline.so` is symlinked next to the engine so the
# package:skyline Linux lookup (`DynamicLibrary.open("libskyline.so")`) resolves.
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=env.sh
source "$SCRIPT_DIR/env.sh"

engine_root="$ENGINE_CHECKOUT/engine/src"
embedder_dir="$engine_root/flutter/shell/platform/embedder"
runtime_root="$ENGINE_REPO_ROOT/native/runtime"
runtime_dest="$embedder_dir/skyline_runtime"
manifest="$runtime_root/sources.txt"
build_file="$embedder_dir/BUILD.gn"
export_file="$embedder_dir/embedder_exports.lst"
link_path="$ENGINE_STAGE/libskyline.so"

# Prints the files of one manifest section (`common` or `embedded`).
list_runtime_sources() {
  awk -v want="$1" '
    /^\[/ { section = $0; gsub(/[\[\]]/, "", section); next }
    /^#/ || NF == 0 { next }
    section == want { print }
  ' "$manifest"
}

check_only=0
do_build=1
runtime_mode=debug
while [ $# -gt 0 ]; do
  case "$1" in
    --check) check_only=1 ;;
    --no-build) do_build=0 ;;
    --runtime-mode)
      [ $# -ge 2 ] || die "--runtime-mode needs a value"
      runtime_mode=$2
      shift
      ;;
    --runtime-mode=*) runtime_mode=${1#*=} ;;
    -h|--help)
      sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done
case "$runtime_mode" in
  debug) ENGINE_STAGE="$ENGINE_DIR/out/linux-x64-debug" ;;
  release) ENGINE_STAGE="$ENGINE_DIR/out/linux-x64-release" ;;
  *) die "unsupported runtime mode: $runtime_mode" ;;
esac
export SKYLINE_ENGINE_STAGE="$ENGINE_STAGE"
link_path="$ENGINE_STAGE/libskyline.so"

[ -d "$embedder_dir" ] || die "missing engine checkout: $embedder_dir (run npm run engine:fetch)"
[ -f "$manifest" ] || die "missing runtime manifest: $manifest"

if [ "$check_only" -eq 1 ]; then
  while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    [ -f "$runtime_dest/$rel" ] || die "missing copied runtime file: $rel"
    cmp -s "$runtime_root/$rel" "$runtime_dest/$rel" ||
      die "stale copied runtime file: $rel (run without --check)"
  done < <(list_runtime_sources common; list_runtime_sources embedded)
  grep -q 'BEGIN skyline runtime' "$build_file" ||
    die "BUILD.gn lacks the generated Skyline runtime block"
  grep -q 'SKYLINE_EMBEDDED=1' "$build_file" ||
    die "BUILD.gn lacks the SKYLINE_EMBEDDED define"
  [ ! -e "$embedder_dir/skyline_runtime.cc" ] ||
    die "legacy skyline_runtime.cc is still present"
  grep -q 'AdjustDecelerationVelocity;' "$export_file" || die "embedder_exports.lst lacks the Skyline exports"
  [ -e "$link_path" ] || die "missing $link_path (run without --check)"
  log "embedded Skyline runtime is installed"
  exit 0
fi

python3 - "$runtime_root" "$runtime_dest" "$embedder_dir" <<'PY'
import re
import shutil
import sys
from pathlib import Path

runtime_root = Path(sys.argv[1])
runtime_dest = Path(sys.argv[2])
embedder_dir = Path(sys.argv[3])
manifest = runtime_root / "sources.txt"

sections = {"common": [], "embedded": []}
section = None
for raw in manifest.read_text(encoding="utf-8").splitlines():
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    match = re.fullmatch(r"\[([a-z]+)\]", line)
    if match:
        section = match.group(1)
        if section not in sections:
            raise SystemExit(f"unknown sources.txt section: {section}")
        continue
    if section is None:
        raise SystemExit(f"runtime source outside a section: {line}")
    sections[section].append(line)

all_files = sections["common"] + sections["embedded"]
cc_files = [name for name in all_files if name.endswith(".cc")]
if not cc_files:
    raise SystemExit("sources.txt lists no translation units")

expected = set(all_files)
# Generated by build-engine.sh from the copies; not a runtime source.
expected.add("skyline_runtime_build_id.hh")
for rel in all_files:
    source = runtime_root / rel
    if not source.is_file():
        raise SystemExit(f"missing runtime source: {source}")
    destination = runtime_dest / rel
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_bytes() != source.read_bytes():
        shutil.copy2(source, destination)

runtime_dest.mkdir(parents=True, exist_ok=True)
for path in sorted(runtime_dest.rglob("*")):
    if path.is_file() and str(path.relative_to(runtime_dest)) not in expected:
        path.unlink()
for path in sorted((p for p in runtime_dest.rglob("*") if p.is_dir()),
                   reverse=True):
    if not any(path.iterdir()):
        path.rmdir()

legacy = embedder_dir / "skyline_runtime.cc"
if legacy.exists():
    legacy.unlink()

build_path = embedder_dir / "BUILD.gn"
build = build_path.read_text(encoding="utf-8")
begin = "# BEGIN skyline runtime (generated by native/engine/patch-skyline-runtime.sh)"
end = "# END skyline runtime (generated)"
config_begin = "# BEGIN skyline runtime config (generated by native/engine/patch-skyline-runtime.sh)"
config_end = "# END skyline runtime config (generated)"
config_block = (
    f"{config_begin}\n"
    f"config(\"skyline_runtime_config\") {{\n"
    f"  defines = [ \"SKYLINE_EMBEDDED=1\" ]\n"
    f"}}\n"
    f"{config_end}\n"
)
if config_begin in build:
    cstart = build.index(config_begin)
    cend = build.index(config_end) + len(config_end) + 1
    build = build[:cstart] + config_block + build[cend:]
else:
    template_anchor = 'template("embedder_source_set") {'
    if template_anchor not in build:
        raise SystemExit("cannot find embedder_source_set template")
    build = build.replace(template_anchor, config_block + "\n" + template_anchor, 1)

sources = "\n".join(f'        "skyline_runtime/{name}",' for name in cc_files)
block = (
    f"    if (target_name == \"embedder\") {{\n"
    f"      {begin}\n"
    f"      sources += [\n{sources}\n      ]\n"
    f"      configs += [ \":skyline_runtime_config\" ]\n"
    f"      {end}\n"
    f"    }}\n"
)
# Remove the legacy single-file block (with or without its Phase 3 comment).
legacy_re = re.compile(
    r'\n    # Phase 3: Skyline runtime[^\n]*\n'
    r'    if \(target_name == "embedder"\) \{\n'
    r'      sources \+= \[ "skyline_runtime\.cc" \]\n'
    r'    \}\n')
build, removed = legacy_re.subn("\n", build, count=1)
if not removed:
    plain_legacy = (
        '\n    if (target_name == "embedder") {\n'
        '      sources += [ "skyline_runtime.cc" ]\n'
        '    }\n'
    )
    build = build.replace(plain_legacy, "\n", 1)

if begin in build:
    start = build.index(begin) - len("    if (target_name == \"embedder\") {\n      ")
    end_marker = build.index(end) + len(end) + len("\n    }\n")
    build = build[:start] + block + build[end_marker:]
else:
    if begin not in build:
        anchor = (
            '      "vsync_waiter_embedder.cc",\n'
            '      "vsync_waiter_embedder.h",\n'
            "    ]\n"
        )
        if anchor not in build:
            raise SystemExit("cannot find embedder BUILD.gn sources anchor")
        build = build.replace(anchor, anchor + "\n" + block, 1)
if build != build_path.read_text(encoding="utf-8"):
    build_path.write_text(build, encoding="utf-8")
    print("patched BUILD.gn")
PY

patch_output=$(python3 - "$embedder_dir" "$ENGINE_REPO_ROOT/spec/kernel-symbols.json" <<'PY'
import json
import sys
from pathlib import Path

embedder_dir = Path(sys.argv[1])
spec_path = Path(sys.argv[2])

export_path = embedder_dir / "embedder_exports.lst"
exports = export_path.read_text(encoding="utf-8")
spec = json.loads(spec_path.read_text(encoding="utf-8"))
names = sorted(entry["name"] for entry in spec["ffi"]["lookupSymbols"])
# Host-injected keyboard channel (not part of the captured FFI table).
names.append("DispatchSkylineKeyEvent")
# Linux live DevTools bridge (addon -> embedded runtime page ops).
names.append("SkylineApplyLiveOps")
# Layout geometry for the appservice selector-query APIs.
names.append("SkylineGetNodeRect")
# Scroll-into-view bridge (`scroll-into-view` WXML property).
names.append("SkylineScrollNodeTo")
names.append("SkylineScrollIntoView")
# Scroll event sink (native ScrollViewUpdateOnScroll* -> addon JS thread).
names.append("SkylineSetScrollEventSink")
# Swiper/picker/input event + programmatic bridge.
names.append("SkylineSetWidgetEventSink")
names.append("SkylineSwiperTo")
names.append("SkylinePickerColumnSetCurrent")
names.append("SkylineSetInputFocus")
# D9: intersection observer / selection / refresher / back interception.
names.append("SkylineSetJsonEventSink")
names.append("SkylineAddIntersectionObserver")
names.append("SkylineRemoveIntersectionObserver")
names.append("SkylineSelectionSetRange")
names.append("SkylineRefresherTriggered")
names.append("SkylineSetNavigateBackInterception")
# D10: accessibility + DevTools automation.
names.append("SkylineSetAccessibilitySink")
names.append("SkylineGetAccessibilityState")
names.append("SkylineRequestAccessibility")
names.append("SkylineDumpElementTree")
names.append("SkylineDumpRenderTree")
names.append("SkylineCollectGarbage")
names.append("SkylineSendMessageToRunner")
names.append("SkylineTakeAppSnapshot")
names.append("SkylineSnapshotNode")
names.append("SkylineSetUserGesture")
names.append("SkylineRelaunchApp")
names.append("SkylineShutdownApplication")
# DevTools Network panel bridge: images/fonts fetch through the pageframe.
names.append("SkylineSetHttpRequestSink")
names.append("SkylineNotifyHttpRequestComplete")
# Safe-area insets for CSS env(safe-area-inset-*).
names.append("SkylineSetSafeAreaInsets")
# Custom-route gesture worklets (navigatorPop/startUserGesture/...) -> Dart.
names.append("SkylineNavigatorPop")
names.append("SkylineStartUserGesture")
names.append("SkylineStopUserGesture")
names.append("SkylineUpdateAnimationController")
# Source fingerprint of the embedded runtime (tools/build-status.js).
names.append("SkylineRuntimeBuildId")
missing = [name for name in names if f"    {name};" not in exports]
if missing:
    anchor = "    kInternalFlutterGpu*;\n"
    if anchor not in exports:
        raise SystemExit("cannot find embedder_exports.lst anchor")
    block = "    # Skyline runtime exports (phase 3)\n" + "".join(
        f"    {name};\n" for name in missing
    )
    exports = exports.replace(anchor, anchor + block, 1)
    export_path.write_text(exports, encoding="utf-8")
    print(f"patched embedder_exports.lst ({len(missing)} symbols)")
PY
)
if [ -n "$patch_output" ]; then
  log "$patch_output"
  # The version script is not a ninja input; force a relink so newly exported
  # Skyline* symbols actually appear in libflutter_engine.so.
  rm -f "$ENGINE_STAGE/libflutter_engine.so"
fi

if [ "$do_build" -eq 1 ]; then
  log "building flutter_engine with the embedded Skyline runtime ($runtime_mode)"
  bash "$SCRIPT_DIR/build-engine.sh" --runtime-mode "$runtime_mode"
fi

[ -f "$ENGINE_STAGE/libflutter_engine.so" ] || die "engine not staged; run npm run engine:build"
ln -sfn "$ENGINE_STAGE/libflutter_engine.so" "$link_path"

expected=$(node -e '
  const fs = require("fs");
  const spec = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
  process.stdout.write(String(spec.ffi.lookupSymbols.length));
' "$ENGINE_REPO_ROOT/spec/kernel-symbols.json")
exported=$(nm -D --defined-only "$ENGINE_STAGE/libflutter_engine.so" |
  awk '{print $NF}' |
  node -e '
    const fs = require("fs");
    const want = new Set(JSON.parse(fs.readFileSync(process.argv[1], "utf8")).ffi.lookupSymbols.map(e => e.name));
    let count = 0;
    for (const line of fs.readFileSync(0, "utf8").split("\n")) {
      if (want.has(line.trim())) count++;
    }
    process.stdout.write(String(count));
  ' "$ENGINE_REPO_ROOT/spec/kernel-symbols.json")
if [ "$exported" != "$expected" ]; then
  die "engine exports $exported/$expected Skyline runtime symbols"
fi
log "embedded Skyline runtime ready: $link_path -> libflutter_engine.so ($exported symbols)"
